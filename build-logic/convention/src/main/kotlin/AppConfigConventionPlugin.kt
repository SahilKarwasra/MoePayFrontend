import com.laarasoft.moepay.convention.pathToPackageName
import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.register
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import java.util.Properties

/**
 * Generates `<module package>.config.AppConfig` into commonMain from `local.properties`.
 *
 * Keys (all optional, defaults target a backend running locally on port 8080):
 *   MOEPAY_BASE_URL_ANDROID  default http://10.0.2.2:8080 (Android emulator -> host machine)
 *   MOEPAY_BASE_URL_IOS      default http://localhost:8080 (iOS simulator shares the host network)
 */
class AppConfigConventionPlugin : Plugin<Project> {

    override fun apply(target: Project) {
        with(target) {
            val localProperties = providers
                .fileContents(rootProject.layout.projectDirectory.file("local.properties"))
                .asText
                .map { text -> Properties().apply { load(text.reader()) } }
                .orElse(Properties())

            fun field(key: String, default: String) =
                localProperties.map { it.getProperty(key, default) }

            val generateAppConfig = tasks.register<GenerateAppConfigTask>("generateAppConfig") {
                packageName.set("${pathToPackageName()}.config")
                fields.put("BASE_URL_ANDROID", field("MOEPAY_BASE_URL_ANDROID", "http://10.0.2.2:8080"))
                fields.put("BASE_URL_IOS", field("MOEPAY_BASE_URL_IOS", "http://localhost:8080"))
                outputDir.set(layout.buildDirectory.dir("generated/appConfig/kotlin"))
            }

            extensions.configure<KotlinMultiplatformExtension> {
                sourceSets.named("commonMain") {
                    kotlin.srcDir(generateAppConfig.flatMap { it.outputDir })
                }
            }
        }
    }
}

@CacheableTask
abstract class GenerateAppConfigTask : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val fields: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
        dir.mkdirs()
        val body = fields.get().toSortedMap().entries.joinToString("\n") { (key, value) ->
            val escaped = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
            "    const val $key: String = \"$escaped\""
        }
        dir.resolve("AppConfig.kt").writeText(
            """
            |// Generated by AppConfigConventionPlugin from local.properties. Do not edit.
            |package $pkg
            |
            |object AppConfig {
            |$body
            |}
            |""".trimMargin()
        )
    }
}
